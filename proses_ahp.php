<?php

session_start();
require_once "koneksi.php";


/*
|--------------------------------------------------------------------------
| 1. Pastikan jenis kelamin sudah dipilih
|--------------------------------------------------------------------------
*/

if (!isset($_SESSION['jenis_kelamin'])) {
    header("Location: pilih_jenis_kelamin.php");
    exit;
}


/*
|--------------------------------------------------------------------------
| 2. Pastikan semua pasangan kriteria sudah dipilih
|--------------------------------------------------------------------------
*/

$required = ['p12', 'p13', 'p23'];

foreach ($required as $r) {

    if (!isset($_POST[$r]) || !is_numeric($_POST[$r])) {

        $_SESSION['pref_error'] =
            "Semua perbandingan kriteria harus dipilih.";

        header("Location: input_preferensi.php");
        exit;
    }
}


/*
|--------------------------------------------------------------------------
| 3. Ambil nilai preferensi pengguna
|--------------------------------------------------------------------------
*/

$p12 = (float) $_POST['p12'];
$p13 = (float) $_POST['p13'];
$p23 = (float) $_POST['p23'];


/*
|--------------------------------------------------------------------------
| 4. Validasi nilai
|--------------------------------------------------------------------------
*/

if ($p12 <= 0 || $p13 <= 0 || $p23 <= 0) {

    $_SESSION['pref_error'] =
        "Nilai preferensi tidak valid.";

    header("Location: input_preferensi.php");
    exit;
}


/*
|--------------------------------------------------------------------------
| 5. Membentuk matriks perbandingan berpasangan AHP
|--------------------------------------------------------------------------
|
| C1 = Arti Nama
| C2 = Tingkat Keunikan
| C3 = Nilai Keislaman
|
*/

$a = [

    [1,        $p12,       $p13],

    [1/$p12,   1,          $p23],

    [1/$p13,   1/$p23,     1]

];


/*
|--------------------------------------------------------------------------
| 6. Menghitung jumlah setiap kolom
|--------------------------------------------------------------------------
*/

$col = [0, 0, 0];

for ($j = 0; $j < 3; $j++) {

    for ($i = 0; $i < 3; $i++) {

        $col[$j] += $a[$i][$j];

    }

}


/*
|--------------------------------------------------------------------------
| 7. Normalisasi matriks
|--------------------------------------------------------------------------
*/

$norm = [
    [0,0,0],
    [0,0,0],
    [0,0,0]
];

$bobot = [0,0,0];

for ($i = 0; $i < 3; $i++) {

    for ($j = 0; $j < 3; $j++) {

        $norm[$i][$j] =
            $a[$i][$j] / $col[$j];

    }

}


/*
|--------------------------------------------------------------------------
| 8. Menghitung bobot prioritas
|--------------------------------------------------------------------------
*/

for ($i = 0; $i < 3; $i++) {

    $bobot[$i] =
        array_sum($norm[$i]) / 3;

}


/*
|--------------------------------------------------------------------------
| 9. Normalisasi bobot agar jumlah = 1
|--------------------------------------------------------------------------
*/

$sum = array_sum($bobot);

if ($sum > 0) {

    for ($i = 0; $i < 3; $i++) {

        $bobot[$i] /= $sum;

    }

}


/*
|--------------------------------------------------------------------------
| 10. Menghitung Weighted Sum / A × W
|--------------------------------------------------------------------------
*/

$aw = [0,0,0];

for ($i = 0; $i < 3; $i++) {

    for ($j = 0; $j < 3; $j++) {

        $aw[$i] +=
            $a[$i][$j] * $bobot[$j];

    }

}


/*
|--------------------------------------------------------------------------
| 11. Menghitung Lambda Max
|--------------------------------------------------------------------------
*/

$lambda_total = 0;

for ($i = 0; $i < 3; $i++) {

    if ($bobot[$i] > 0) {

        $lambda_total +=
            $aw[$i] / $bobot[$i];

    }

}

$lambda = $lambda_total / 3;


/*
|--------------------------------------------------------------------------
| 12. Menghitung Consistency Index (CI)
|--------------------------------------------------------------------------
*/

$n = 3;

$ci = ($lambda - $n) / ($n - 1);


/*
|--------------------------------------------------------------------------
| 13. Random Index untuk n = 3
|--------------------------------------------------------------------------
*/

$ri = 0.58;


/*
|--------------------------------------------------------------------------
| 14. Menghitung Consistency Ratio (CR)
|--------------------------------------------------------------------------
*/

$cr = $ci / $ri;


/*
|--------------------------------------------------------------------------
| 15. Menentukan status konsistensi
|--------------------------------------------------------------------------
*/

$konsisten = ($cr <= 0.10);


/*
|--------------------------------------------------------------------------
| 16. Jangan menghentikan proses jika CR > 0,1
|--------------------------------------------------------------------------
|
| Ini bagian penting.
|
| Baik konsisten maupun kurang konsisten,
| hasil AHP tetap disimpan dan diproses.
|
*/

if ($konsisten) {

    $status_konsistensi =
        "Konsisten";

} else {

    $status_konsistensi =
        "Kurang konsisten";

}


/*
|--------------------------------------------------------------------------
| 17. Simpan seluruh hasil AHP ke SESSION
|--------------------------------------------------------------------------
*/

$_SESSION['ahp'] = [

    'matrix' =>
        $a,

    'normalisasi' =>
        $norm,

    'bobot' =>
        $bobot,

    'lambda' =>
        $lambda,

    'ci' =>
        $ci,

    'cr' =>
        $cr,

    'konsisten' =>
        $konsisten,

    'status_konsistensi' =>
        $status_konsistensi,

    'p12' =>
        $p12,

    'p13' =>
        $p13,

    'p23' =>
        $p23

];


/*
|--------------------------------------------------------------------------
| 18. Tetap lanjut ke halaman hasil
|--------------------------------------------------------------------------
*/

header("Location: hasil_rekomendasi.php");
exit;

?>